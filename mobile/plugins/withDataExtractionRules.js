/**
 * Config plugin (#44): no app data leaves the phone in a cloud backup or an Android 12+
 * device-to-device transfer.
 *
 * `allowBackup="false"` already stops cloud backup, but device-to-device transfer IGNORES it on
 * Android 12+ (API 31+). This adds `android:dataExtractionRules` pointing at a rules file that
 * excludes every data domain from both <cloud-backup> and <device-transfer>, so the secure-store
 * values (wrapped data key, sealed refresh token, installation and user id) are not copied at all.
 * Without it they would be copied but unreadable (the Keystore key does not move).
 *
 * No dependency: the rules file is written by this plugin at prebuild.
 */
const fs = require('node:fs');
const path = require('node:path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RESOURCE = '@xml/data_extraction_rules';
const FILE = path.join('app', 'src', 'main', 'res', 'xml', 'data_extraction_rules.xml');

// Every domain the rules format knows (credential-protected and device-protected storage).
const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

function rulesXml() {
  const excludes = DOMAINS.map((domain) => `    <exclude domain="${domain}" path="." />`).join('\n');
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withDataExtractionRules.js (#44). Nothing is backed up or transferred. -->',
    '<data-extraction-rules>',
    '  <cloud-backup>',
    excludes,
    '  </cloud-backup>',
    '  <device-transfer>',
    excludes,
    '  </device-transfer>',
    '</data-extraction-rules>',
    '',
  ].join('\n');
}

function withDataExtractionRules(config) {
  config = withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (application === undefined) {
      throw new Error('withDataExtractionRules: AndroidManifest.xml has no <application>');
    }
    const current = application.$['android:dataExtractionRules'];
    if (current !== undefined && current !== RESOURCE) {
      // Another plugin (for example expo-secure-store's) set different rules: refuse to guess.
      throw new Error(`withDataExtractionRules: android:dataExtractionRules is already "${current}"`);
    }
    application.$['android:dataExtractionRules'] = RESOURCE;
    return mod;
  });
  return withDangerousMod(config, [
    'android',
    async (mod) => {
      const target = path.join(mod.modRequest.platformProjectRoot, FILE);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, rulesXml());
      return mod;
    },
  ]);
}

module.exports = withDataExtractionRules;
module.exports.DOMAINS = DOMAINS;
module.exports.rulesXml = rulesXml;
